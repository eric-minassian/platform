// Writes src/login-glyphs.ts: Geist SemiBold outlines for the characters app
// names and domains use, so the engine can draw managed login logos as paths.
// Cognito takes logos only as images, and an SVG image can't load a web font.
//
//   pnpm --filter @ericminassian/platform-engine gen:login-glyphs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { type Font, type PathCommand, create } from 'fontkit';
import { decompress } from 'wawoff2';

const CHARS = 'abcdefghijklmnopqrstuvwxyz0123456789-.';
const WEIGHT = 600;

// The console's own Geist (variable). fontkit instances variations only from
// TrueType bytes, so the WOFF2 is decoded first.
const require = createRequire(import.meta.url);
const file = require.resolve('@fontsource-variable/geist/files/geist-latin-wght-normal.woff2');
const opened = create(Buffer.from(await decompress(readFileSync(file))));
if (!('getVariation' in opened)) throw new Error(`${file} is a font collection`);
const font: Font = opened.getVariation({ wght: WEIGHT });

const glyph = (ch: string) => font.glyphForCodePoint(ch.codePointAt(0)!);

/** SVG path data in font units, y down (the baseline at 0), whole units. */
function pathData(commands: PathCommand[]): string {
  const letter = { moveTo: 'M', lineTo: 'L', quadraticCurveTo: 'Q', bezierCurveTo: 'C', closePath: 'Z' };
  return commands
    .map(({ command, args }) => {
      const points = args.map((n, i) => Math.round(i % 2 ? -n : n) || 0);
      return letter[command] + points.join(' ');
    })
    .join('');
}

const glyphs: Record<string, { advance: number; d: string }> = {};
for (const ch of CHARS) {
  const g = glyph(ch);
  glyphs[ch] = { advance: Math.round(g.advanceWidth), d: pathData(g.path.commands) };
}

// Pair kerning from the font's GPOS, without ligatures (logos draw each glyph).
const kerning: Record<string, number> = {};
for (const a of CHARS) {
  for (const b of CHARS) {
    const run = font.layout(a + b, { liga: false, clig: false, calt: false });
    const first = run.positions[0];
    if (run.glyphs.length !== 2 || !first) throw new Error(`"${a}${b}" didn't lay out as two glyphs`);
    const kern = Math.round(first.xAdvance - glyph(a).advanceWidth);
    if (kern) kerning[a + b] = kern;
  }
}

const out = fileURLToPath(new URL('../src/login-glyphs.ts', import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/login-glyphs.ts; don't edit.
// Geist (c) Vercel, SIL Open Font License 1.1: https://github.com/vercel/geist-font

/** Outlines in font units, y down from the baseline; \`kerning\` adjusts a pair's first advance. */
export interface GlyphSet {
  unitsPerEm: number;
  capHeight: number;
  glyphs: Record<string, { advance: number; d: string }>;
  kerning: Record<string, number>;
}

/** Geist at weight ${WEIGHT}: ${CHARS.split('').join(' ')} */
export const GEIST_SEMIBOLD: GlyphSet = ${JSON.stringify({
    unitsPerEm: font.unitsPerEm,
    capHeight: Math.round(font.capHeight),
    glyphs,
    kerning,
  })};
`,
);
execFileSync('pnpm', ['exec', 'oxfmt', out], { stdio: 'inherit' });
console.log(`wrote ${out}`);
